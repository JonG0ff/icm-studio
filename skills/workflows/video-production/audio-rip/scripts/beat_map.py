#!/usr/bin/env python3
"""Beat map: per-frame band energy and hit frames for a music clip.

Writes a TypeScript module that a Remotion composition imports, so music
reactivity is baked data and renders the same every time.

Usage:
  python3 beat_map.py SONG.mp3 OUT.ts --start 27.36 --bars 8 --bpm 70.86 \
    [--fps 30] [--beats-per-bar 4] [--clip OUT.mp3]

- --start is the first downbeat (seconds into the song). Frame 0 is that time.
- --clip also cuts the same span to an mp3 for the composition to play.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, find_peaks, sosfilt

SAMPLE_RATE = 22050
BANDS = {"low": (None, 150), "mid": (150, 2000), "high": (2500, 8000)}
RELEASE_SECONDS = 0.18
NORM_PERCENTILE = 98
HIT_PERCENTILE = 96
MIN_HIT_GAP_SECONDS = 0.12


def decode(song: Path) -> np.ndarray:
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "song.wav"
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-i", str(song), "-ac", "1", "-ar", str(SAMPLE_RATE), str(wav)],
            check=True,
        )
        _, data = wavfile.read(wav)
    return data.astype(np.float32) / 32768.0


def band_filter(x: np.ndarray, lo: float | None, hi: float) -> np.ndarray:
    if lo is None:
        sos = butter(4, hi, btype="low", fs=SAMPLE_RATE, output="sos")
    else:
        sos = butter(4, [lo, hi], btype="band", fs=SAMPLE_RATE, output="sos")
    return sosfilt(sos, x)


def frame_rms(y: np.ndarray, hop: int) -> np.ndarray:
    n = len(y) // hop
    return np.sqrt((y[: n * hop].reshape(n, hop) ** 2).mean(axis=1))


def with_release(env: np.ndarray, fps: int) -> np.ndarray:
    """Instant attack, exponential release. Reads as a pulse, not flicker."""
    decay = np.exp(-1.0 / (RELEASE_SECONDS * fps))
    out = np.empty_like(env)
    level = 0.0
    for i, v in enumerate(env):
        level = max(v, level * decay)
        out[i] = level
    return out


def normalize(env: np.ndarray) -> np.ndarray:
    peak = np.percentile(env, NORM_PERCENTILE)
    return np.clip(env / peak, 0.0, 1.0) if peak > 0 else env


def hit_frames(env: np.ndarray, fps: int) -> list[int]:
    onset = np.maximum(np.diff(env, prepend=env[0]), 0.0)
    peaks, _ = find_peaks(
        onset,
        height=np.percentile(onset, HIT_PERCENTILE),
        distance=max(1, int(MIN_HIT_GAP_SECONDS * fps)),
    )
    return [int(p) for p in peaks]


def build_map(x: np.ndarray, start: float, seconds: float, fps: int) -> dict:
    hop = SAMPLE_RATE // fps
    a = int(start * SAMPLE_RATE)
    z = a + int(seconds * SAMPLE_RATE) + hop
    if z > len(x):
        raise ValueError(f"Clip ends at {start + seconds:.2f}s, past the song's {len(x) / SAMPLE_RATE:.2f}s.")
    frames = int(round(seconds * fps))
    result: dict = {"frames": frames}
    for name, (lo, hi) in BANDS.items():
        raw = frame_rms(band_filter(x, lo, hi)[a:z], hop)[:frames]
        result[name] = normalize(raw)
        result[f"{name}Hits"] = hit_frames(raw, fps)
        result[name] = with_release(result[name], fps)
    return result


def to_ts(m: dict, args: argparse.Namespace) -> str:
    def arr(values) -> str:
        return json.dumps([round(float(v), 3) for v in values], separators=(",", ":"))

    beat = 60.0 / args.bpm
    return f"""/**
 * Generated by skills/workflows/video-production/audio-rip/scripts/beat_map.py.
 * Do not hand-edit. Re-run the script to change it.
 *
 * Song span {args.start:.2f}s for {args.bars} bars at {args.bpm} BPM, {args.fps} fps.
 * Bands are 0-1 with instant attack and a {RELEASE_SECONDS}s release.
 */
export const BEAT_MAP = {{
  fps: {args.fps},
  frames: {m["frames"]},
  songStartSeconds: {args.start},
  bpm: {args.bpm},
  beatFrames: {beat * args.fps:.4f},
  beatsPerBar: {args.beats_per_bar},
  bars: {args.bars},
  low: {arr(m["low"])},
  mid: {arr(m["mid"])},
  high: {arr(m["high"])},
  lowHits: {json.dumps(m["lowHits"])},
  midHits: {json.dumps(m["midHits"])},
  highHits: {json.dumps(m["highHits"])},
}} as const;
"""


def cut_clip(song: Path, out: Path, start: float, seconds: float) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-ss", f"{start}", "-t", f"{seconds}", "-i", str(song),
         "-c:a", "libmp3lame", "-q:a", "0", str(out)],
        check=True,
    )


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("song", type=Path)
    p.add_argument("out", type=Path)
    p.add_argument("--start", type=float, required=True, help="First downbeat, seconds into the song")
    p.add_argument("--bars", type=int, required=True)
    p.add_argument("--bpm", type=float, required=True)
    p.add_argument("--fps", type=int, default=30)
    p.add_argument("--beats-per-bar", type=int, default=4)
    p.add_argument("--clip", type=Path, help="Also cut the span to this mp3")
    args = p.parse_args()

    if not args.song.is_file():
        print(f"Song not found: {args.song}", file=sys.stderr)
        return 1
    if args.bpm <= 0 or args.bars <= 0 or args.start < 0:
        print("--bpm and --bars must be positive and --start must be >= 0.", file=sys.stderr)
        return 1

    seconds = args.bars * args.beats_per_bar * 60.0 / args.bpm
    try:
        m = build_map(decode(args.song), args.start, seconds, args.fps)
    except (subprocess.CalledProcessError, ValueError) as err:
        print(f"Beat map failed: {err}", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(to_ts(m, args))
    if args.clip:
        cut_clip(args.song, args.clip, args.start, seconds)
    print(f"Wrote {args.out} ({m['frames']} frames, {seconds:.2f}s). "
          f"Hits: low {len(m['lowHits'])}, mid {len(m['midHits'])}, high {len(m['highHits'])}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
